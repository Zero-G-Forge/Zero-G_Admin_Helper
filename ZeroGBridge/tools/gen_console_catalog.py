# Generates Core/ConsoleCatalogData.cs from Ray's console command sheet (CSV export).
# Usage: python tools/gen_console_catalog.py <telnet_commands.csv>
# Sheet columns: Command, Description, Is telnet? (V = works over telnet / server console), Permission level
import csv, os, re, sys
SRC = sys.argv[1] if len(sys.argv) > 1 else 'telnet_commands.csv'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Core', 'ConsoleCatalogData.cs')

# commands that change the server, game state or a player (ZAH puts these behind CONFIRM)
CHANGES = set('''ai aimanager alliances armor ban changemode defragsavegame destroy destroyme detach entity exec faction
finishbp give godmode initadmin itemmenu kick level loadplayfield marker mergestructs op pda playfield poimanager
prefabactivate regenerate repair replaceblocks resetcore sector sectors setdevicespublic setposition setrole setrotation
si spawnanyblueprint statuseffect statuseffectremove struct teleport terraineditor ticks time traders unban undock
uresource weather weathersv wipe remoteex saveandexit say stoppf'''.split())
# forms that only read when sent with no arguments (e.g. "ticks" shows ticks, "ticks set 5" changes them)
SAFE_NO_ARGS = set('ticks time saveandexit stoppf'.split())
BLOCKED = {
  'replaceblocks': 'Blocked by the bridge: the command sheet says never run replaceblocks on a server.',
  'changemode': 'Blocked by the bridge: changemode does not work in multiplayer.',
}
# telnet-only commands from the Empyrion wiki Telnet_Commands page (not in the sheet)
EXTRA = [
  ('instances', 'Shows information of all running instances', 'V', '?'),
  ('plys', 'Shows all players in the game', 'V', '?'),
  ('remoteex', "Send an in-game console command to a player (cl=<client id>) or playfield (pf=<process id>); runs without the player's permission check", 'V', '?'),
  ('saveandexit', "Saves the game and exits after a timeout in minutes (max 15). 'saveandexit cancel' cancels; no argument shows a scheduled exit", 'V', '?'),
  ('say', "Sends a chat message: say 'text' (all), say f:<faction> 'text', say p:<client id> 'text'", 'V', '?'),
  ('servers', 'Lists all connected playfield servers', 'V', '?'),
  ('stoppf', "Stops a playfield server (or all) after an optional timeout; 'stoppf cancel' cancels; no argument shows a scheduled stop", 'V', '?'),
]

def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\r', '').replace('\n', ' ') + '"'

def minlevel(p):
    m = re.match(r'\s*(\d+)', p or '')
    return m.group(1) if m else '-1'

rows = []
with open(SRC, newline='', encoding='utf-8') as f:
    r = csv.reader(f); next(r)
    for line in r:
        if not line or not line[0].strip(): continue
        rows.append((line[0].strip(), line[1].strip(), line[2].strip(), line[3].strip(), 'sheet'))
names = {re.split(r'\s+or\s+', x[0])[0].strip().lower() for x in rows}
for e in EXTRA:
    if e[0] not in names: rows.append(e + ('telnet_wiki',))

out = ['// =====================================================================',
'// MODULE: ZeroGBridge/Core/ConsoleCatalogData.cs',
"// DESCRIPTION: 1.6.0 console / telnet command list. Made from Ray's command sheet",
'//              (telnet_commands.csv) plus the telnet-only commands from the Empyrion wiki.',
'//              Generated by tools/gen_console_catalog.py; edit the sheet and regenerate,',
'//              or edit a row here by hand.',
'// Columns: sheet name, description, server capable (V), permission, changes server,',
'//          safe with no arguments, blocked reason (null = not blocked), source',
'// =====================================================================',
'',
'namespace ZeroGBridge',
'{',
'    internal static class ConsoleCatalogData',
'    {',
'        internal static readonly ConsoleCommandInfoRow[] Rows =',
'        {']
for (raw, desc, v, perm, src) in rows:
    key = re.split(r'\s+or\s+', raw)[0].strip().lower()
    base = key.split()[0]
    out.append('            new ConsoleCommandInfoRow(%s, %s, %s, %s, %s, %s, %s, %s),' % (
        cs(raw), cs(desc), 'true' if v.upper() == 'V' else 'false', cs(perm),
        'true' if base in CHANGES else 'false', 'true' if base in SAFE_NO_ARGS else 'false',
        cs(BLOCKED[base]) if base in BLOCKED else 'null', cs(src)))
out += ['        };', '    }', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(rows), 'rows')
